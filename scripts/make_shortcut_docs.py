"""Write the keyboard shortcut tables from the main window's commands (issue #119).

Two outputs, both generated from the same run, so they can't disagree:

- ``docs/guide/keyboard-shortcuts.md``: the guide page, with every command and its shortcut.
- ``web/src/generated/shortcuts.json``: the web front end's copy (W2.1 slice (f),
  docs/web/design/W1.3.md §5): command id -> label, default key sequences and the icon name
  (W4.3a S1; null when the command has no bundled icon).

A unit test fails when a committed output no longer matches the app.

    uv run python scripts/make_shortcut_docs.py          # rewrite both files
    uv run python scripts/make_shortcut_docs.py --check  # exit 1 when either is out of date
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "guide" / "keyboard-shortcuts.md"
WEB_OUTPUT = ROOT / "web" / "src" / "generated" / "shortcuts.json"

INTRO = """\
<!-- Generated by scripts/make_shortcut_docs.py from the application's commands. Do not edit. -->

# Keyboard shortcuts

These are the default shortcuts of every command. To change one, open **Edit ▸ Keyboard
Shortcuts…** (or press Ctrl+Shift+P and search for the command). Your changes are kept on this
computer, and **Default** or **Reset All** restores these values.

Commands with no shortcut can still be run from the menus, the ribbon, the command palette
(Ctrl+Shift+P) or the search box at the top right of the ribbon.

| Command | Shortcut |
| --- | --- |
"""


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _menu_label(text: str) -> str:
    """Menu text without mnemonics: "&&" is a literal ampersand, "&" marks the mnemonic."""
    placeholder = "\x01"
    label = text.replace("&&", placeholder).replace("&", "")
    return label.replace(placeholder, "&").removesuffix("…").strip()


def render_outputs() -> tuple[str, str]:
    """The guide page and the web table for the current commands. Builds the main window
    offscreen, once."""
    from PySide6.QtWidgets import QApplication

    from pdfeditor.ui.main_window import MainWindow
    from pdfeditor.ui.shortcuts import action_id, command_actions

    app = QApplication.instance() or QApplication(sys.argv[:1])
    window = MainWindow()
    try:
        manager = window.shortcuts
        rows: list[tuple[str, str, str]] = []
        commands: dict[str, dict[str, object]] = {}
        seen: set[str] = set()
        for action in command_actions(window):
            key = action_id(action)
            if key in seen:  # the same command in a menu and on the ribbon
                continue
            seen.add(key)
            label = _menu_label(action.text())
            sequences = list(manager.defaults.get(key, ()))
            rows.append((label.lower(), label, ", ".join(sequences) or "None"))
            # The bundled icon's name (data/icons), so the web ribbon shows the same icon as the
            # desktop. Null when the action has none; the web catalog overrides it for its own ids.
            icon_name = action.icon().name()
            commands[key] = {"label": label, "keys": sequences, "icon": icon_name or None}
        rows.sort()
        body = "".join(f"| {_cell(label)} | {_cell(keys)} |\n" for _, label, keys in rows)
    finally:
        window.close()
        window.deleteLater()
        app.processEvents()
    web = json.dumps({"commands": dict(sorted(commands.items()))}, indent=2) + "\n"
    return INTRO + body, web


def _isolate_profile() -> None:
    """Keep settings and logs out of the user's profile while the window is built."""
    from PySide6.QtCore import QSettings

    data = tempfile.mkdtemp(prefix="pdfeditor-docs-")
    os.environ["PDFEDITOR_DATA_DIR"] = data
    QSettings.setDefaultFormat(QSettings.Format.IniFormat)
    QSettings.setPath(QSettings.Format.IniFormat, QSettings.Scope.UserScope, data)


def main(argv: list[str]) -> int:
    _isolate_profile()
    text, web = render_outputs()
    outputs = [(OUTPUT, text), (WEB_OUTPUT, web)]
    if "--check" in argv:
        stale = [path for path, body in outputs if _read(path) != body]
        for path in stale:
            print(f"{path} is out of date: run scripts/make_shortcut_docs.py", file=sys.stderr)
        if stale:
            return 1
        print("shortcut outputs are up to date")
        return 0
    for path, body in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8", newline="\n")
        print(f"wrote {path}")
    return 0


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else ""


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
