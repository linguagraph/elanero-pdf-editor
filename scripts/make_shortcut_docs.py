"""Write ``docs/guide/keyboard-shortcuts.md`` from the main window's commands (issue #119).

The page lists every command with its default shortcut. It is generated, not written by hand:
a unit test fails when the committed page no longer matches the app.

    uv run python scripts/make_shortcut_docs.py          # rewrite the page
    uv run python scripts/make_shortcut_docs.py --check  # exit 1 when it is out of date
"""

from __future__ import annotations

import os
import sys
import tempfile
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "guide" / "keyboard-shortcuts.md"

INTRO = """\
<!-- Generated by scripts/make_shortcut_docs.py from the application's commands. Do not edit. -->

# Keyboard shortcuts

These are the default shortcuts of every command. To change one, open **Edit ▸ Keyboard
Shortcuts…** (or press Ctrl+Shift+P and search for the command). Your changes are kept on this
computer, and **Default** or **Reset All** restores these values.

Commands with no shortcut can still be run from the menus, the ribbon, the command palette
(Ctrl+Shift+P) or the search box at the top right of the ribbon.

| Command | Shortcut |
| --- | --- |
"""


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _menu_label(text: str) -> str:
    """Menu text without mnemonics: "&&" is a literal ampersand, "&" marks the mnemonic."""
    placeholder = "\x01"
    label = text.replace("&&", placeholder).replace("&", "")
    return label.replace(placeholder, "&").removesuffix("…").strip()


def render_page() -> str:
    """The page for the current commands. Builds the main window offscreen, once."""
    from PySide6.QtWidgets import QApplication

    from pdfeditor.ui.main_window import MainWindow
    from pdfeditor.ui.shortcuts import action_id, command_actions

    app = QApplication.instance() or QApplication(sys.argv[:1])
    window = MainWindow()
    try:
        manager = window.shortcuts
        rows: list[tuple[str, str, str]] = []
        seen: set[str] = set()
        for action in command_actions(window):
            key = action_id(action)
            if key in seen:  # the same command in a menu and on the ribbon
                continue
            seen.add(key)
            label = _menu_label(action.text())
            keys = ", ".join(manager.defaults.get(key, ())) or "None"
            rows.append((label.lower(), label, keys))
        rows.sort()
        body = "".join(f"| {_cell(label)} | {_cell(keys)} |\n" for _, label, keys in rows)
    finally:
        window.close()
        window.deleteLater()
        app.processEvents()
    return INTRO + body


def _isolate_profile() -> None:
    """Keep settings and logs out of the user's profile while the window is built."""
    from PySide6.QtCore import QSettings

    data = tempfile.mkdtemp(prefix="pdfeditor-docs-")
    os.environ["PDFEDITOR_DATA_DIR"] = data
    QSettings.setDefaultFormat(QSettings.Format.IniFormat)
    QSettings.setPath(QSettings.Format.IniFormat, QSettings.Scope.UserScope, data)


def main(argv: list[str]) -> int:
    _isolate_profile()
    text = render_page()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is out of date: run scripts/make_shortcut_docs.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT} is up to date")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
