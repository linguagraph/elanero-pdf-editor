"""Generate the third-party licence notice of the web build (W9.5b).

It reads only committed inputs: the lock of the web app (its runtime npm packages, those without
``dev: true``), ``web/spike/versions.json`` (the pinned Pyodide and PyMuPDF versions),
``scripts/web_licences.toml`` (the copyright line of each npm package, and the non-npm components
of the engine) and ``scripts/licence_texts/`` (the standard text of each licence; AGPL-3.0 is the
repository's ``LICENSE``). It writes ``web/app/public/THIRD_PARTY_LICENSES.txt``: plain text, so
the browser shows it without running any script, and copied into ``dist/`` beside the service
worker so it is precached for offline use.

Nothing is read from ``node_modules`` and nothing is installed, so the notice can be built on a
clean checkout. The output is deterministic (sorted, no timestamps), so ``--check`` can compare it
byte for byte:

    uv run python scripts/make_web_licences.py          # rewrite the file
    uv run python scripts/make_web_licences.py --check  # exit 1 when it is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
APP_LOCK = ROOT / "web" / "app" / "package-lock.json"
VERSIONS = ROOT / "web" / "spike" / "versions.json"
INPUTS = ROOT / "scripts" / "web_licences.toml"
TEXTS = ROOT / "scripts" / "licence_texts"
AGPL_TEXT = ROOT / "LICENSE"
OUTPUT = ROOT / "web" / "app" / "public" / "THIRD_PARTY_LICENSES.txt"

# Licence ids that share one text: both AGPL versions print the repository's LICENSE once.
_TEXT_ID = {"AGPL-3.0-only": "AGPL-3.0", "AGPL-3.0-or-later": "AGPL-3.0"}
# The version pins of versions.json that the TOML must repeat, with the component to review.
_PINNED = (("pyodide", "Pyodide"), ("pymupdf", "PyMuPDF"))

_HEADER = """\
THIRD-PARTY LICENCE NOTICE: ELANERO WEB BUILD
=============================================

Elanero's web build is free software under the GNU Affero General Public License, version 3 or
later (AGPL-3.0-or-later). The source code of this build is at the commit linked from the About
page of the app. The text of the AGPL is in the licence texts at the end of this file.

This file lists the software that the web build ships to the browser: the engine (Python and
WebAssembly, with its bundled libraries), the JavaScript packages, and the licences they use. It is
generated by scripts/make_web_licences.py from committed inputs; do not edit it by hand.

An entry whose note starts "To confirm" has not yet been checked against its source."""


class NoticeError(Exception):
    """Every problem found while building the notice, sorted, so one run reports them all."""

    def __init__(self, problems: list[str]) -> None:
        self.problems = sorted(set(problems))
        super().__init__("\n".join(self.problems))


@dataclass(frozen=True)
class Entry:
    """One listed package or component. ``url`` and ``note`` are optional."""

    name: str
    version: str
    licence: str
    copyright: tuple[str, ...]
    url: str | None = None
    note: str | None = None


def _text_id(licence: str) -> str:
    return _TEXT_ID.get(licence, licence)


def _text_path(licence: str, texts: Path, agpl: Path) -> Path | None:
    """The file holding the standard text of a licence id, or None when it has none."""
    key = _text_id(licence)
    if key == "AGPL-3.0":
        return agpl if agpl.is_file() else None
    path = texts / f"{key}.txt"
    return path if path.is_file() else None


def _read_text(path: Path) -> str:
    # Read as bytes and normalise the newlines, the way make_web_types.py does, so a checkout with
    # CRLF endings (or a Windows write) compares equal.
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def _runtime_packages(lock: Path) -> dict[str, tuple[str, Any]]:
    """Name -> (version, licence field) of each package the browser ships (not ``dev: true``)."""
    data = json.loads(_read_text(lock))
    packages: dict[str, tuple[str, Any]] = {}
    for key, info in data.get("packages", {}).items():
        if key == "" or info.get("dev"):
            continue
        # The name follows the last node_modules/ (nested installs, scoped names included).
        name = key.rsplit("node_modules/", 1)[-1]
        packages[name] = (str(info.get("version", "")), info.get("license"))
    return packages


def _component(raw: dict[str, Any], problems: list[str]) -> Entry | None:
    fields = ("name", "version", "license", "copyright")
    missing = [field for field in fields if field not in raw]
    if missing:
        problems.append(f"web_licences.toml: a [[component]] has no {', '.join(missing)}")
        return None
    copyright_lines = raw["copyright"]
    if isinstance(copyright_lines, str):
        copyright_lines = [copyright_lines]
    return Entry(
        name=str(raw["name"]),
        version=str(raw["version"]),
        licence=str(raw["license"]),
        copyright=tuple(str(line) for line in copyright_lines),
        url=raw.get("url"),
        note=raw.get("note"),
    )


def _check_licence(owner: str, licence: Any, texts: Path, agpl: Path, problems: list[str]) -> None:
    if not isinstance(licence, str) or not licence:
        problems.append(f"{owner}: no licence field (an SPDX identifier is needed)")
    elif _text_path(licence, texts, agpl) is None:
        problems.append(
            f"{owner}: licence {licence!r} has no standard text in scripts/licence_texts/"
        )


def make(
    lock: Path = APP_LOCK,
    versions: Path = VERSIONS,
    inputs: Path = INPUTS,
    texts: Path = TEXTS,
    agpl: Path = AGPL_TEXT,
) -> str:
    """The notice text. Raises NoticeError listing every problem in the inputs."""
    problems: list[str] = []
    spec = tomllib.loads(_read_text(inputs))
    pins = json.loads(_read_text(versions))
    for key, label in _PINNED:
        if spec.get(key) != pins.get(key):
            problems.append(
                f"web_licences.toml {key} = {spec.get(key)!r} but web/spike/versions.json "
                f"{key} = {pins.get(key)!r}: review the {label} components"
            )

    components: list[Entry] = []
    for raw in spec.get("component", []):
        entry = _component(raw, problems)
        if entry is not None:
            components.append(entry)
            _check_licence(f"component {entry.name!r}", raw.get("license"), texts, agpl, problems)

    runtime = _runtime_packages(lock)
    npm_info: dict[str, Any] = spec.get("npm", {})
    npm: list[Entry] = []
    for name, (version, licence) in runtime.items():
        _check_licence(f"npm package {name!r}", licence, texts, agpl, problems)
        copyright_entry = npm_info.get(name, {})
        if "copyright" not in copyright_entry:
            problems.append(f'npm package {name!r} has no [npm."{name}"] copyright entry')
            continue
        npm.append(
            Entry(
                name=name,
                version=version,
                licence=str(licence),
                copyright=(str(copyright_entry["copyright"]),),
            )
        )
    for name in sorted(set(npm_info) - set(runtime)):
        problems.append(
            f'web_licences.toml [npm."{name}"] names a package the web app lock does not ship'
        )

    if problems:
        raise NoticeError(problems)
    return _render(components, npm, texts, agpl)


def _render_entry(entry: Entry, with_url: bool) -> list[str]:
    lines = [entry.name, f"  Version: {entry.version}", f"  Licence: {entry.licence}"]
    if with_url and entry.url:
        lines.append(f"  URL: {entry.url}")
    lines.append(f"  Copyright: {'; '.join(entry.copyright)}")
    if entry.note:
        lines.append(f"  Note: {entry.note}")
    return lines


def _render(components: list[Entry], npm: list[Entry], texts: Path, agpl: Path) -> str:
    out: list[str] = [_HEADER, ""]

    out += ["1. ENGINE AND BUNDLED COMPONENTS", "-" * 60, ""]
    for entry in sorted(components, key=lambda e: e.name):
        out += [*_render_entry(entry, with_url=True), ""]

    out += ["2. JAVASCRIPT PACKAGES (RUNTIME, FROM web/app/package-lock.json)", "-" * 60, ""]
    for entry in sorted(npm, key=lambda e: e.name):
        out += [*_render_entry(entry, with_url=False), ""]

    # Each licence text once, with the entries that use it.
    users: dict[str, list[str]] = {}
    for entry in [*components, *npm]:
        users.setdefault(_text_id(entry.licence), []).append(entry.name)
    out += ["3. LICENCE TEXTS", "-" * 60]
    for licence in sorted(users):
        path = _text_path(licence, texts, agpl)
        assert path is not None  # make() checked every licence used above
        body = _read_text(path).rstrip("\n")
        out += [
            "",
            f"--- {licence} ---",
            f"Used by: {', '.join(sorted(set(users[licence])))}",
            "",
            body,
        ]
    return "\n".join(out) + "\n"


def _report(err: NoticeError) -> None:
    sys.stderr.write("the third-party licence notice cannot be built:\n")
    for problem in err.problems:
        sys.stderr.write(f"  - {problem}\n")


def check(path: Path = OUTPUT) -> int:
    """0 when the committed notice matches a fresh build, else 1 (with the reason on stderr)."""
    try:
        fresh = make()
    except NoticeError as err:
        _report(err)
        return 1
    current = _read_text(path) if path.is_file() else None
    if current != fresh:
        sys.stderr.write(
            f"{path} is missing or out of date.\nrun: uv run python scripts/make_web_licences.py\n"
        )
        return 1
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 when the committed notice is out of date"
    )
    args = parser.parse_args(argv)
    if args.check:
        return check(OUTPUT)
    try:
        text = make()
    except NoticeError as err:
        _report(err)
        return 1
    OUTPUT.write_bytes(text.encode("utf-8"))
    sys.stdout.write(f"wrote {OUTPUT}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
