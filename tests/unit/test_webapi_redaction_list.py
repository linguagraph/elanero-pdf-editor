"""The web's ``redaction.list`` call (W7.4b S2): every redaction mark in the document, read-only.

The list is the document's marks, so a mark drawn in this tab, a mark removed by undo and a mark
already in the file all appear (or disappear) the same way. The saved files are checked by pikepdf
and pypdfium2 through ``tests.hostcheck.record`` (AGENTS.md round-trip and leak rules), so this
module imports neither at module level: the host replay runs it under Pyodide.
"""

from __future__ import annotations

from collections.abc import Iterator
from typing import Any

import pytest

from pdfeditor.model import platform as model_platform
from pdfeditor.webapi import jobs
from pdfeditor.webapi.errors import INVALID_ARGS, NO_DOCUMENT
from pdfeditor.webapi.platform import configure_web
from pdfeditor.webapi.registry import REGISTRY
from tests.hostcheck import record
from tests.unit.test_webapi_jobs import (
    apply,
    binary,
    call,
    call_raw,
    error,
    ok,
    open_data,
    prepare,
    run_job,
)

REDACT = "redaction.apply"
SECRETS = ("jane.example@example.com", "123-45-6789")
PUBLIC = "Public paragraph that must survive."
RECT = {"x0": 60.0, "y0": 90.0, "x1": 250.0, "y1": 200.0}
RED = {"r": 1.0, "g": 0.0, "b": 0.0}
RESTYLED = "EXEMPT"
# The pre-existing fixture's named mark (generated by scripts/make_fixtures.py).
NAMED = "preexisting-email"
NAMED_RECT = {"x0": 70.0, "y0": 116.0, "x1": 330.0, "y1": 132.0}


@pytest.fixture
def web() -> Iterator[None]:
    previous = model_platform.current()
    configure_web()
    try:
        yield
    finally:
        jobs.PREPARED.clear()
        REGISTRY.close_all()
        model_platform.configure(previous)


def listed(handle: str) -> dict[str, Any]:
    result: dict[str, Any] = ok(call("redaction.list", {"handle": handle}))
    return result


def run(handle: str, name: str, args: dict[str, Any]) -> dict[str, Any]:
    result: dict[str, Any] = ok(call("actions.run", {"handle": handle, "name": name, "args": args}))
    assert result["executed"] is True
    return result


def draw(handle: str) -> str:
    """Draws one area mark with the default style, and returns its name."""
    args = {"areas": [{"page": 0, "rect": RECT}]}
    value = run(handle, "redaction.mark", args)["value"]
    assert len(value) == 1
    return str(value[0]["name"])


def save_copy(handle: str) -> bytes:
    reply, out = call_raw("save.save_bytes", {"handle": handle, "mode": "copy"})
    result = ok(reply)
    assert result["verified"] is True
    return binary(result["data"], out)


def test_a_fresh_document_has_no_marks(web: None, fixture_pdf: Any) -> None:
    handle = open_data(fixture_pdf("images").read_bytes(), "images.pdf")
    assert listed(handle) == {"marks": [], "truncated": False}


def test_a_drawn_mark_is_listed_with_the_default_style(web: None, fixture_pdf: Any) -> None:
    handle = open_data(fixture_pdf("images").read_bytes(), "images.pdf")
    name = draw(handle)
    result = listed(handle)
    assert result["truncated"] is False
    (mark,) = result["marks"]
    assert mark["page"] == 0
    assert mark["name"] == name
    assert mark["rect"] == RECT
    assert mark["fill"] == {"r": 0.0, "g": 0.0, "b": 0.0, "a": 1.0}
    assert mark["overlay_text"] == ""
    assert mark["text_color"] == {"r": 1.0, "g": 1.0, "b": 1.0, "a": 1.0}
    assert mark["locked"] is False


def test_undo_removes_the_mark_from_the_list(web: None, fixture_pdf: Any) -> None:
    handle = open_data(fixture_pdf("images").read_bytes(), "images.pdf")
    draw(handle)
    assert len(listed(handle)["marks"]) == 1
    assert ok(call("actions.undo", {"handle": handle}))["label"]
    assert listed(handle)["marks"] == []


def test_a_restyle_shows_in_the_list(web: None, fixture_pdf: Any) -> None:
    handle = open_data(fixture_pdf("images").read_bytes(), "images.pdf")
    name = draw(handle)
    args = {"marks": [{"page": 0, "name": name}], "fill": RED, "overlay_text": RESTYLED}
    run(handle, "redaction.restyle_marks", args)
    (mark,) = listed(handle)["marks"]
    assert mark["fill"] == {"r": 1.0, "g": 0.0, "b": 0.0, "a": 1.0}
    assert mark["overlay_text"] == RESTYLED


def test_the_pre_existing_marks_are_listed_with_their_names(web: None, fixture_pdf: Any) -> None:
    handle = open_data(fixture_pdf("redact_marks_preexisting").read_bytes(), "pre.pdf")
    marks = listed(handle)["marks"]
    assert [m["page"] for m in marks] == [0, 0]
    named, unnamed = marks
    assert named["name"] == NAMED
    assert named["rect"] == NAMED_RECT
    assert unnamed["name"] and unnamed["name"] != NAMED  # the engine's synthetic name
    assert unnamed["overlay_text"] == ""


def test_the_listed_names_are_accepted_by_restyle_and_remove(web: None, fixture_pdf: Any) -> None:
    handle = open_data(fixture_pdf("redact_marks_preexisting").read_bytes(), "pre.pdf")
    refs = [{"page": m["page"], "name": m["name"]} for m in listed(handle)["marks"]]
    run(handle, "redaction.restyle_marks", {"marks": refs, "overlay_text": RESTYLED})
    assert all(m["overlay_text"] == RESTYLED for m in listed(handle)["marks"])
    run(handle, "redaction.remove_marks", {"marks": refs})
    assert listed(handle)["marks"] == []


def test_an_unknown_handle_is_no_document(web: None) -> None:
    assert error(call("redaction.list", {"handle": "nope"}))["code"] == NO_DOCUMENT


def test_an_extra_param_is_invalid_args(web: None, fixture_pdf: Any) -> None:
    handle = open_data(fixture_pdf("images").read_bytes(), "images.pdf")
    assert error(call("redaction.list", {"handle": handle, "extra": 1}))["code"] == INVALID_ARGS


def test_a_restyled_mark_saves_its_style(web: None, fixture_pdf: Any) -> None:
    handle = open_data(fixture_pdf("images").read_bytes(), "images.pdf")
    name = draw(handle)
    args = {"marks": [{"page": 0, "name": name}], "fill": RED, "overlay_text": RESTYLED}
    run(handle, "redaction.restyle_marks", args)
    data = save_copy(handle)
    record(
        "redact_annot_pikepdf",
        data,
        page=0,
        mark=name,
        fill=[1.0, 0.0, 0.0],
        overlay=RESTYLED,
        text=[1.0, 1.0, 1.0],
    )
    record("render_size_pdfium", data, page=0, scale=1)
    record("page_count_pikepdf", data, pages=1)


def test_the_apply_of_all_marks_leaks_nothing_and_keeps_the_style(
    web: None, fixture_pdf: Any
) -> None:
    handle = open_data(fixture_pdf("redact_marks_preexisting").read_bytes(), "pre.pdf")
    restyle = {"marks": [{"page": 0, "name": NAMED}], "fill": RED, "overlay_text": RESTYLED}
    run(handle, "redaction.restyle_marks", restyle)
    # Apply All (marks null): the marks from the file are applied too, not only drawn ones.
    action = {"name": REDACT, "args": {"marks": None}}
    prepared, copy = prepare(handle, "action", action)
    assert prepared["mutating"] is True
    reply, out = run_job("action", action, copy)
    result = ok(reply)
    assert result["value"]["leaks"] == []
    document = binary(result["document"], out)
    applied = ok(apply(handle, prepared["token"], document, result["label"], True))
    assert applied["applied"] is True
    assert listed(handle)["marks"] == []

    data = save_copy(handle)
    for secret in SECRETS:
        record("streams_lack_pikepdf", data, needle=secret)
        record("doc_text_lacks_pdfium", data, text=secret)
    record("doc_text_contains_pdfium", data, text=PUBLIC)
    record("red_pixels_pdfium", data, page=0, clip=[70.0, 116.0, 330.0, 132.0], minimum=500)
