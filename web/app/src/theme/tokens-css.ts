import {
  BREAKPOINTS_PX,
  COLOURS,
  FONT_SIZES_PX,
  LAYOUT_PX,
  RADII_PX,
  SPACE_STEPS,
  SPACE_UNIT_PX,
  type ColourToken,
} from './tokens.ts';

// Variable names are the token names in kebab case: `surfaceAlt` -> `--color-surface-alt`.
function colourVar(token: ColourToken): string {
  return `--color-${token.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`;
}

function colourDeclarations(scheme: 'light' | 'dark', indent: string): string[] {
  const values = COLOURS[scheme];
  return (Object.keys(values) as ColourToken[]).map(
    (token) => `${indent}${colourVar(token)}: ${values[token]};`,
  );
}

function metricDeclarations(indent: string): string[] {
  const lines: string[] = [];
  for (let n = 1; n <= SPACE_STEPS; n++) {
    lines.push(`${indent}--space-${n}: ${n * SPACE_UNIT_PX}px;`);
  }
  for (const [name, px] of Object.entries(RADII_PX)) {
    lines.push(`${indent}--radius-${name}: ${px}px;`);
  }
  for (const [name, px] of Object.entries(FONT_SIZES_PX)) {
    lines.push(`${indent}--font-size-${name}: ${px}px;`);
  }
  for (const [name, px] of Object.entries(BREAKPOINTS_PX)) {
    lines.push(`${indent}--breakpoint-${name}: ${px}px;`);
  }
  for (const [name, px] of Object.entries(LAYOUT_PX)) {
    const kebab = name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
    lines.push(`${indent}--layout-${kebab}: ${px}px;`);
  }
  return lines;
}

// Windows high contrast (and any forced-colours user setting) overrides colours with the system
// palette. Every colour token maps to a system colour keyword here, so the components that read
// the variables get the system colours without their own rules. Borders stay visible because
// they use CanvasText, not a tint. Each keyword is a CSS system colour, so the user's chosen
// high-contrast theme is honoured. The selector is `:root:root` so it outranks the dark blocks,
// which use two-part selectors (`:root:not([data-theme])` and `:root[data-theme]`).
const FORCED_COLOURS: Record<ColourToken, string> = {
  window: 'Canvas',
  surface: 'ButtonFace',
  surfaceAlt: 'ButtonFace',
  border: 'CanvasText',
  borderStrong: 'CanvasText',
  text: 'CanvasText',
  textMuted: 'CanvasText',
  textDisabled: 'GrayText',
  accent: 'Highlight',
  onAccent: 'HighlightText',
  accentText: 'LinkText',
  focusRing: 'CanvasText',
  danger: 'CanvasText',
  success: 'CanvasText',
  warning: 'CanvasText',
  brand: 'LinkText',
};

function forcedColoursBlock(): string[] {
  const body = '  ';
  const inner = '    ';
  return [
    '@media (forced-colors: active) {',
    `${body}:root:root {`,
    ...(Object.keys(FORCED_COLOURS) as ColourToken[]).map(
      (token) => `${inner}${colourVar(token)}: ${FORCED_COLOURS[token]};`,
    ),
    `${body}}`,
    '',
    `${body}/* Forced colours recolour outlines too; a system colour keeps the focus ring visible on Canvas. */`,
    `${body}:focus-visible {`,
    `${inner}outline: 2px solid CanvasText;`,
    `${inner}outline-offset: 2px;`,
    `${body}}`,
    '}',
    '',
  ];
}

// Light is the base. Dark applies (a) when the system prefers it and the user has not chosen
// Light, and (b) when the user chose Dark. A user who chose Light stays light either way.
export function renderTokensCss(): string {
  const body = '  ';
  const inner = '    ';
  const lines = [
    '/* Generated by web/app/scripts/generate-tokens.ts from src/theme/tokens.ts. Do not edit. */',
    ':root {',
    `${body}color-scheme: light;`,
    ...colourDeclarations('light', body),
    ...metricDeclarations(body),
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    `${body}:root:not([data-theme='light']) {`,
    `${inner}color-scheme: dark;`,
    ...colourDeclarations('dark', inner),
    `${body}}`,
    '}',
    '',
    ":root[data-theme='dark'] {",
    `${body}color-scheme: dark;`,
    ...colourDeclarations('dark', body),
    '}',
    '',
    ...forcedColoursBlock(),
  ];
  return lines.join('\n');
}
